import { expect, test } from '@playwright/test';

test('commitment fixture accepts two contexts and exposes its precise limitation', async ({ page }) => {
  await page.goto('.');
  await expect(page.locator('#kc-output')).toBeHidden();
  for (const tag of ['16', '32']) {
    await page.locator('#kc-tag').selectOption(tag);
    await page.locator('#kc-case').selectOption('collision');
    await page.locator('#kc-run').click();
    await expect(page.locator('#kc-a')).toHaveText('ACCEPTED');
    await expect(page.locator('#kc-b')).toHaveText('ACCEPTED');
    await expect(page.locator('#kc-status')).toHaveClass(/danger/);
    await expect(page.locator('#kc-status')).toContainText('BOTH ACCEPTED');
    await expect(page.locator('#kc-limit')).toContainText('key commitment failed');
    await expect(page.locator('#kc-limit')).toBeVisible();
    const finalBits = await page.locator('#kc-trace tr').last().locator('td').allTextContents();
    expect(finalBits.map(Number)).toEqual([0, 0, 0, 0, 0, 0]);
    const bytes = (await page.locator('#kc-bytes').textContent())!;
    const read = (label: string) => bytes.split('\n').find(l => l.startsWith(label + ': '))!.slice(label.length + 2);
    expect(read('Key A')).not.toBe(read('Key B'));
    expect(read('AD A')).not.toBe(read('AD B'));
    expect(read('Tag sent to both')).toHaveLength(Number(tag) * 2);
    expect(read('Tag freshly generated by B')).toBe(read('Tag sent to both'));
    expect(read('Ciphertext freshly generated by B')).toBe(read('Ciphertext sent to both'));
    expect(read('Plaintext A')).toBe('bf9c8cbfae09e8faa362c38090b75327');
    expect(read('Plaintext B')).toBe(read('Plaintext A'));
    if (tag === '16') expect(read('Ciphertext sent to both') + read('Tag sent to both')).toBe('5f7400731e881d84ae0a18e2169b6e98b08d5cb1749f5380f6e09b0f331d42f0');
  }
});

test('commitment controls reject B and input changes retire old results', async ({ page }) => {
  await page.goto('.');
  for (const tag of ['16', '32']) {
    await page.locator('#kc-tag').selectOption(tag);
    for (const scenario of ['same-ad', 'tampered-ad']) {
      await page.locator('#kc-case').selectOption(scenario);
      await page.locator('#kc-run').click();
      await expect(page.locator('#kc-a')).toHaveText('ACCEPTED');
      await expect(page.locator('#kc-b')).toHaveText('REJECTED');
      await expect(page.locator('#kc-status')).toContainText('Only 1');
      await expect(page.locator('#kc-bytes')).toContainText('Plaintext B: not released');
      const bits = await page.locator('#kc-trace tr').last().locator('td').allTextContents();
      expect(bits.map(Number).some(n => n > 0)).toBe(true);
      await page.locator('#kc-case').dispatchEvent('change');
      await expect(page.locator('#kc-output')).toBeVisible();
      await page.locator('#kc-case').selectOption('collision');
      await expect(page.locator('#kc-output')).toBeHidden();
      await expect(page.locator('#kc-status')).toContainText('retired');
    }
  }
});
